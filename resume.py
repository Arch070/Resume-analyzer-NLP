def make_synthetic_resume_dataset(n_samples=1000, pos_ratio=0.5, random_state=42):
    random.seed(random_state)
    np.random.seed(random_state)

    ds_phrases = [
        "machine learning", "deep learning", "data science", "data analysis",
        "python", "pandas", "numpy", "scikit-learn", "tensorflow", "pytorch",
        "modeling", "feature engineering", "statistical analysis", "natural language processing",
        "classification", "regression", "clustering", "SQL", "big data", "spark"
    ]

    non_ds_phrases = [
        "accounting", "sales", "marketing", "customer service", "biology", "chemistry",
        "product management", "graphic design", "illustrator", "photoshop", "content writing",
        "teaching", "cashier", "retail", "hospitality"
    ]

    texts, labels = [], []
    for i in range(n_samples):
        if random.random() < pos_ratio:
            words = random.choices(ds_phrases + non_ds_phrases, weights=[3]*len(ds_phrases) + [1]*len(non_ds_phrases), k=random.randint(20, 60))
            labels.append(1)
        else:
            words = random.choices(non_ds_phrases + ds_phrases, weights=[3]*len(non_ds_phrases) + [0.5]*len(ds_phrases), k=random.randint(20, 60))
            labels.append(0)
        texts.append(" ".join(words))

    return pd.DataFrame({"text": texts, "label": labels})

def train_level1(df: pd.DataFrame, model_type="logreg"):
    X = df['text'].values
    y = df['label'].values
    X_train, X_test, y_train, y_test = train_test_split(X, y, stratify=y, test_size=0.2, random_state=42)

    if model_type == 'logreg':
        clf = LogisticRegression(max_iter=1000)
    else:
        clf = MultinomialNB()

    pipe = Pipeline([
        ('tfidf', TfidfVectorizer(ngram_range=(1,2), min_df=2)),
        ('clf', clf)
    ])

    pipe.fit(X_train, y_train)
    y_pred = pipe.predict(X_test)

    print("Classification report:")
    print(classification_report(y_test, y_pred))
    print("Confusion matrix:")
    print(confusion_matrix(y_test, y_pred))

    return pipe

